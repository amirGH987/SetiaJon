const intro = document.getElementById("intro");
const story = document.getElementById("story");
const ending = document.getElementById("ending");

const startButton = document.getElementById("startButton");
const nextButton = document.getElementById("nextButton");
const backButton = document.getElementById("backButton");
const replayButton = document.getElementById("replayButton");
const heartButton = document.getElementById("heartButton");

const chapterLabel = document.getElementById("chapterLabel");
const progressPercent = document.getElementById("progressPercent");
const progressFill = document.getElementById("progressFill");

const chapterTag = document.getElementById("chapterTag");
const chapterIcon = document.getElementById("chapterIcon");
const chapterTitle = document.getElementById("chapterTitle");
const chapterText = document.getElementById("chapterText");
const finalLetter = document.getElementById("finalLetter");

const heartRain = document.getElementById("heartRain");

let currentChapter = 0;

function createStars() {
  const container = document.getElementById("stars");
  const symbols = ["✦", "·", "✧", "♡"];

  for (let i = 0; i < 35; i++) {
    const star = document.createElement("span");

    star.className = "star";
    star.textContent = symbols[Math.floor(Math.random() * symbols.length)];
    star.style.left = `${Math.random() * 100}%`;
    star.style.top = `${Math.random() * 100}%`;
    star.style.fontSize = `${8 + Math.random() * 13}px`;
    star.style.animationDelay = `${Math.random() * 3}s`;

    container.appendChild(star);
  }
}

function showChapter() {
  const chapter = chapters[currentChapter];

  chapterTag.textContent = chapter.tag;
  chapterIcon.textContent = chapter.icon;
  chapterTitle.textContent = chapter.title;
  chapterText.textContent = chapter.text;

  const percent = Math.round(
    ((currentChapter + 1) / chapters.length) * 100
  );

  chapterLabel.textContent =
    `صفحه‌ی ${currentChapter + 1} از ${chapters.length}`;

  progressPercent.textContent = `${percent}٪`;
  progressFill.style.width = `${percent}%`;

  backButton.disabled = currentChapter === 0;

  if (currentChapter === chapters.length - 1) {
    nextButton.textContent = "رفتن به حرف آخر ♡";
  } else {
    nextButton.innerHTML = 'صفحه‌ی بعد <span>←</span>';
  }

  const card = document.getElementById("letterCard");
  card.style.animation = "none";
  void card.offsetWidth;
  card.style.animation = "cardIn .55s ease both";
}

function startStory() {
  intro.classList.add("hidden");
  ending.classList.add("hidden");
  story.classList.remove("hidden");

  currentChapter = 0;
  showChapter();

  window.scrollTo({ top: 0, behavior: "smooth" });
}

function nextChapter() {
  if (currentChapter < chapters.length - 1) {
    currentChapter++;
    showChapter();
  } else {
    showEnding();
  }

  window.scrollTo({ top: 0, behavior: "smooth" });
}

function previousChapter() {
  if (currentChapter > 0) {
    currentChapter--;
    showChapter();
  }

  window.scrollTo({ top: 0, behavior: "smooth" });
}

function showEnding() {
  story.classList.add("hidden");
  ending.classList.remove("hidden");

  finalLetter.textContent = chapters[chapters.length - 1].text;

  window.scrollTo({ top: 0, behavior: "smooth" });
}

function replayStory() {
  ending.classList.add("hidden");
  intro.classList.remove("hidden");

  currentChapter = 0;
  progressFill.style.width = "0%";
  heartRain.innerHTML = "";

  window.scrollTo({ top: 0, behavior: "smooth" });
}

function makeHearts() {
  const heartSymbols = ["💗", "♡", "💖", "💕", "🤍", "✧"];

  for (let i = 0; i < 32; i++) {
    const heart = document.createElement("span");

    heart.className = "rain-heart";
    heart.textContent =
      heartSymbols[Math.floor(Math.random() * heartSymbols.length)];

    heart.style.left = `${Math.random() * 100}%`;
    heart.style.animationDelay = `${Math.random() * 2}s`;
    heart.style.animationDuration = `${2.5 + Math.random() * 2}s`;

    heartRain.appendChild(heart);

    setTimeout(() => heart.remove(), 5500);
  }
}

startButton.addEventListener("click", startStory);
nextButton.addEventListener("click", nextChapter);
backButton.addEventListener("click", previousChapter);
replayButton.addEventListener("click", replayStory);
heartButton.addEventListener("click", makeHearts);

createStars();
